import http from 'node:http';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { randomBytes, timingSafeEqual } from 'node:crypto';
import { execFile } from 'node:child_process';
import { BrowserLauncher, availableBrowsers } from './lib/browser-launcher.js';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const STATIC = new Map([
  ['/', ['public/index.html', 'text/html; charset=utf-8']],
  ['/app.js', ['public/app.js', 'text/javascript; charset=utf-8']],
  ['/styles.css', ['public/styles.css', 'text/css; charset=utf-8']],
  ['/session.js', ['lib/session.js', 'text/javascript; charset=utf-8']],
]);

function send(res, status, body, type = 'application/json; charset=utf-8') {
  res.writeHead(status, { 'Content-Type': type });
  res.end(type.startsWith('application/json') ? JSON.stringify(body) : body);
}

async function readJSON(req) {
  let size = 0;
  const parts = [];
  for await (const chunk of req) {
    size += chunk.length;
    if (size > 160000) throw new Error('请求内容过大。');
    parts.push(chunk);
  }
  try { return JSON.parse(Buffer.concat(parts).toString('utf8')); }
  catch { throw new Error('请求格式不正确。'); }
}

export async function startServer({ port = 0, manager = new BrowserLauncher(), browserProvider = availableBrowsers } = {}) {
  const key = randomBytes(32).toString('hex');
  let origin;
  const server = http.createServer(async (req, res) => {
    res.setHeader('Cache-Control', 'no-store');
    res.setHeader('X-Content-Type-Options', 'nosniff');
    res.setHeader('X-Frame-Options', 'DENY');
    res.setHeader('Referrer-Policy', 'no-referrer');
    res.setHeader('Content-Security-Policy', "default-src 'self'; script-src 'self'; style-src 'self'; connect-src 'self'; img-src 'self' data:; object-src 'none'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'");
    if (req.headers.host !== new URL(origin).host || (req.headers.origin && req.headers.origin !== origin)) {
      return send(res, 403, { error: '拒绝来自其他来源的请求。' });
    }
    const route = new URL(req.url, origin).pathname;
    try {
      if (route.startsWith('/api/')) {
        const supplied = Buffer.from(String(req.headers['x-local-key'] || ''));
        const expected = Buffer.from(key);
        if (supplied.length !== expected.length || !timingSafeEqual(supplied, expected)) return send(res, 403, { error: '本地访问密钥无效，请从启动入口重新打开工具。' });
        if (req.method === 'GET' && route === '/api/config') return send(res, 200, { browsers: await browserProvider() });
        if (req.method === 'GET' && route === '/api/status') return send(res, 200, manager.snapshot());
        if (req.method !== 'POST') return send(res, 405, { error: '不支持的请求方法。' });
        if (!(req.headers['content-type'] || '').startsWith('application/json')) return send(res, 415, { error: '需要 JSON 请求。' });
        if (route === '/api/launch') {
          const data = await readJSON(req);
          if (!data || typeof data !== 'object' || Array.isArray(data) || Object.keys(data).length !== 1 ||
              !['chrome', 'msedge', 'firefox'].includes(data.browser)) {
            throw new Error('只接受浏览器选项；本版本不接收令牌、网址或启动参数。');
          }
          return send(res, 200, await manager.start(data.browser));
        }
        return send(res, 404, { error: '没有这个接口。' });
      }
      if (req.method !== 'GET') return send(res, 405, { error: '不支持的请求方法。' });
      const asset = STATIC.get(route);
      if (!asset) return send(res, 404, { error: '页面不存在。' });
      send(res, 200, await readFile(path.join(ROOT, asset[0])), asset[1]);
    } catch (error) {
      // Error messages generated by our validation never echo user input.
      const safe = error instanceof Error && !/[\r\n]/.test(error.message) && error.message.length < 180 ? error.message : '操作未完成，请重试。';
      send(res, 400, { error: safe });
    }
  });
  server.requestTimeout = 45000;
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', resolve);
  });
  origin = `http://127.0.0.1:${server.address().port}`;
  return { server, origin, key, url: `${origin}/#${key}`, close: async () => {
    // Ordinary browser windows belong to the user; stopping the UI must not kill them.
    server.closeIdleConnections();
    await new Promise(resolve => server.close(resolve));
  } };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const app = await startServer();
  console.log('GPT AutoLogintor 已启动，仅监听本机。');
  console.log('正在打开操作界面。关闭此终端或按 Ctrl+C 可停止服务。');
  if (!process.argv.includes('--no-open')) {
    // This is an interactive UI explicitly requested by the user. No credential in the URL.
    execFile('powershell.exe', ['-NoProfile', '-NonInteractive', '-Command', `Start-Process '${app.url}'`], { windowsHide: true }, error => {
      if (error) console.log(`无法自动打开界面。请在本机浏览器打开：${app.url}`);
    });
  } else console.log(`本地界面：${app.url}`);
  let stopping = false;
  const stop = async () => { if (stopping) return; stopping = true; await app.close(); process.exit(0); };
  process.on('SIGINT', stop);
  process.on('SIGTERM', stop);
}
